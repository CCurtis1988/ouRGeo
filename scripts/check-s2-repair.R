# Downloads and builds CRAN S2 in a disposable library. The normal library is
# only read; no app session or user's installed package is replaced.
if (Sys.info()[["sysname"]] != "Linux") stop("This source-build acceptance check runs on Linux")
root <- normalizePath(".")
work <- tempfile("ourgeo-s2-repair-", tmpdir = "/tmp")
dir.create(work)
lib <- file.path(work, "library")
dir.create(lib)
original <- find.package("s2")
native <- file.path(original, "libs", paste0("s2", .Platform$dynlib.ext))
before <- tools::md5sum(native)
stopifnot(file.copy(original, lib, recursive = TRUE))
copied_native <- file.path(lib, "s2", "libs", paste0("s2", .Platform$dynlib.ext))
stopifnot(file.rename(copied_native, paste0(copied_native, ".disabled")))
profile <- file.path(work, "profile.R")
writeLines(paste0(".libPaths(", paste(deparse(c(lib, .libPaths())), collapse = ""), ")"), profile)
Sys.setenv(R_PROFILE_USER = profile, R_LIBS_USER = lib)
rscript <- file.path(R.home("bin"), "Rscript")
script <- file.path(root, "r", "health-check.R")
probe <- function() system2(rscript, c(shQuote(script), "s2"), stdout = TRUE, stderr = TRUE)
bad <- probe()
stopifnot(any(grepl("OURGEO_HEALTH\ts2\tFALSE", bad)), any(grepl(lib, bad, fixed = TRUE)))
log <- file.path(work, "repair.log")
cat("Rebuilding isolated S2; progress log: ", log, "\n", sep = "")
status <- system2(rscript, c(shQuote(script), "repair", "s2"), stdout = log, stderr = log)
if (status != 0L) stop("Repair failed; inspect ", log)
good <- probe()
stopifnot(any(grepl("OURGEO_HEALTH\ts2\tTRUE", good)), identical(before, tools::md5sum(native)))
cat(paste(good, collapse = "\n"), "\n")
cat("Fresh-process engine check passed after CRAN source repair. Normal S2 binary unchanged.\n")
